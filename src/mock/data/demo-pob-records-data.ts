/**
 * Sample records for the demo pob records screens (vessel / barge check-in, crew entry, location
 * override), taken from the original ADNOC LMS demo. Locations are seed codes
 * (seeds/locations.json); vessels and barges are seed fleet registrations (seeds/fleet.json).
 */
export interface CrewMember {
  optima: string;
  name: string;
  role: string;
  employer: string;
  category: string;
  nationality: string;
  hsePassportExpiry: string;
}
export interface CrewSeed {
  id: string;
  optima: string;
  locationCode: string;
  vessel: string;
  onBoardAt: string;
  until: string;
  recordedBy: string;
}
export interface VesselSeed {
  id: string;
  name: string;
  type: 'Vessel' | 'Barge';
  locationCode: string;
}
export interface BoardingSeed {
  id: string;
  vesselId: string;
  name: string;
  optima: string;
  company: string;
  role: string;
  boardedAt: string;
  recordedBy: string;
}
export interface OverrideSeed {
  id: string;
  name: string;
  optima: string;
  locationCode: string;
  date: string;
  comment: string;
  recordedBy: string;
}
export interface PersonSeed {
  optima: string;
  name: string;
  locationCode: string;
}

